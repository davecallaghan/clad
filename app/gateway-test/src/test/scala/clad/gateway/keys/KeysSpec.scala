package clad.gateway.keys

import org.scalatest.funsuite.AnyFunSuite
import java.nio.file.{Files, Path, Paths}
import java.nio.file.attribute.PosixFilePermission

class KeysSpec extends AnyFunSuite:
  test("generate once, load, sign, verify; the private key is mode 600; the key id is 16 hex") {
    val dir = Files.createTempDirectory("keys")
    assert(Keys.generate(dir, "components") == Right(true))
    assert(Keys.generate(dir, "components") == Right(false))
    val perms = Files.getPosixFilePermissions(dir.resolve("components.ed25519"))
    assert(perms == java.util.Set.of(PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE))
    val kms = Keys.load(dir, "components").fold(fail(_), identity)
    val pem = Keys.publicPem(dir, "components").fold(fail(_), identity)
    assert(kms.keyId.matches("[0-9a-f]{16}") && Keys.keyIdOf(pem) == Right(kms.keyId))
    val sig = kms.sign("sha256:abc".getBytes("UTF-8")).fold(e => fail(e.toString), identity)
    assert(kms.verify("sha256:abc".getBytes("UTF-8"), sig) == Right(true))
  }

  test("generate leaves exactly the two key files, the private one still mode 600") {
    val dir = Files.createTempDirectory("keys")
    assert(Keys.generate(dir, "supervisor") == Right(true))
    val names = Files.list(dir).toArray.map(p => p.asInstanceOf[Path].getFileName.toString).toSet
    assert(names == Set("supervisor.ed25519", "supervisor.ed25519.pub.pem"))
    assert(Files.getPosixFilePermissions(dir.resolve("supervisor.ed25519")) ==
      java.util.Set.of(PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE))
    assert(Keys.load(dir, "supervisor").isRight)
  }

  test("generate when the key exists leaves both files byte-identical") {
    val dir = Files.createTempDirectory("keys")
    assert(Keys.generate(dir, "components") == Right(true))
    val before = List("components.ed25519", "components.ed25519.pub.pem").map(n => Files.readAllBytes(dir.resolve(n)).toList)
    assert(Keys.generate(dir, "components") == Right(false))
    val after = List("components.ed25519", "components.ed25519.pub.pem").map(n => Files.readAllBytes(dir.resolve(n)).toList)
    assert(before == after)
  }

  test("writeNew onto an existing private key is a Left, replaces nothing and leaves no temp file") {
    val dir = Files.createTempDirectory("keys")
    val priv = dir.resolve("components.ed25519")
    Files.writeString(priv, "winner")
    assert(Keys.writeNew(dir, "components").isLeft)
    assert(Files.readString(priv) == "winner")
    assert(!Files.exists(dir.resolve("components.ed25519.pub.pem")))
    assert(Files.list(dir).count() == 1L)
  }

  test("a key pair written by personal_finance's Python generate_keypair loads, with the same key id") {
    // Fixture generated by src.governance.signing.generate_keypair; test fixture only.
    val pythonKeyId = "27bbdc90ff9d75c4" // key_id_of_public_pem of the fixture's public key
    val dir = Paths.get(getClass.getResource("/keys/components.ed25519").toURI).getParent
    val kms = Keys.load(dir, "components").fold(fail(_), identity)
    assert(kms.keyId == pythonKeyId)
    val pem = Keys.publicPem(dir, "components").fold(fail(_), identity)
    assert(Keys.keyIdOf(pem) == Right(pythonKeyId))
  }

  test("failures are Left, never thrown") {
    val dir = Files.createTempDirectory("keys")
    assert(Keys.load(dir, "components").isLeft)
    assert(Keys.publicPem(dir, "components").isLeft)
    assert(Keys.keyIdOf("not a pem !!!").isLeft)
    assert(Keys.keyIdOf("-----BEGIN PUBLIC KEY-----\nAAAA\n-----END PUBLIC KEY-----\n").isLeft)
    Files.writeString(dir.resolve("components.ed25519"), "garbage")
    Files.writeString(dir.resolve("components.ed25519.pub.pem"), "garbage")
    assert(Keys.load(dir, "components").isLeft)
    val notADir = Files.createTempFile("file", "")
    assert(Keys.generate(notADir, "components").isLeft)
  }
